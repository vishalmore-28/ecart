-- ecart schema for POSTGRESQL (Neon, Render, local). Run automatically at start-up (IF NOT EXISTS, safe to re-run).

CREATE SEQUENCE IF NOT EXISTS seq_users START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_categories START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_products START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_addresses START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_orders START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_order_items START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_order_events START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_reviews START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS seq_audit_log START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(20),
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(10) DEFAULT 'USER' NOT NULL,
  active SMALLINT DEFAULT 1 NOT NULL,
  failed_attempts INTEGER DEFAULT 0 NOT NULL,
  locked_until TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS categories (
  id INTEGER PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  icon VARCHAR(16),
  CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES categories(id),
  name VARCHAR(200) NOT NULL,
  brand VARCHAR(80),
  description VARCHAR(2000),
  price NUMERIC(10,2) NOT NULL,
  mrp NUMERIC(10,2) NOT NULL,
  stock INTEGER DEFAULT 0 NOT NULL,
  image_url VARCHAR(500),
  active SMALLINT DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS cart_items (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  qty INTEGER NOT NULL,
  PRIMARY KEY (user_id, product_id)
);

CREATE TABLE IF NOT EXISTS wishlist (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, product_id)
);

CREATE TABLE IF NOT EXISTS addresses (
  id INTEGER PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  full_name VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  line1 VARCHAR(200) NOT NULL,
  line2 VARCHAR(200),
  city VARCHAR(80) NOT NULL,
  state VARCHAR(80) NOT NULL,
  pincode VARCHAR(10) NOT NULL,
  is_default SMALLINT DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS coupons (
  code VARCHAR(30) PRIMARY KEY,
  percent SMALLINT NOT NULL,
  min_order NUMERIC(10,2) DEFAULT 0 NOT NULL,
  max_discount NUMERIC(10,2),
  active SMALLINT DEFAULT 1 NOT NULL
);

CREATE TABLE IF NOT EXISTS shop_orders (
  id INTEGER PRIMARY KEY,
  order_no VARCHAR(30) NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id),
  status VARCHAR(15) DEFAULT 'PLACED' NOT NULL,
  subtotal NUMERIC(10,2) NOT NULL,
  discount NUMERIC(10,2) DEFAULT 0 NOT NULL,
  tax NUMERIC(10,2) DEFAULT 0 NOT NULL,
  shipping NUMERIC(10,2) DEFAULT 0 NOT NULL,
  total NUMERIC(10,2) NOT NULL,
  coupon_code VARCHAR(30),
  ship_name VARCHAR(100) NOT NULL,
  ship_phone VARCHAR(20) NOT NULL,
  ship_address VARCHAR(600) NOT NULL,
  payment_method VARCHAR(10) NOT NULL,
  payment_status VARCHAR(10) NOT NULL,
  txn_ref VARCHAR(40),
  card_last4 VARCHAR(4),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_orders_no UNIQUE (order_no)
);

CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES shop_orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  name VARCHAR(200) NOT NULL,
  price NUMERIC(10,2) NOT NULL,
  qty INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS order_events (
  id INTEGER PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES shop_orders(id) ON DELETE CASCADE,
  status VARCHAR(15) NOT NULL,
  note VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS reviews (
  id INTEGER PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL,
  title VARCHAR(120),
  body VARCHAR(1500),
  verified SMALLINT DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_review UNIQUE (product_id, user_id)
);

CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER PRIMARY KEY,
  user_id INTEGER,
  action VARCHAR(40) NOT NULL,
  detail VARCHAR(255),
  ip VARCHAR(45),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ===== Seller / distributor marketplace (added in v3). Safe to re-run. =====

CREATE TABLE IF NOT EXISTS sellers (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  shop_name VARCHAR(120) NOT NULL,
  business_type VARCHAR(30) NOT NULL,
  pan VARCHAR(10) NOT NULL,
  gstin VARCHAR(15),
  gst_registered SMALLINT DEFAULT 1 NOT NULL,
  address_line1 VARCHAR(200) NOT NULL,
  address_line2 VARCHAR(200),
  city VARCHAR(80) NOT NULL,
  state VARCHAR(80) NOT NULL,
  pincode VARCHAR(10) NOT NULL,
  bank_holder VARCHAR(100) NOT NULL,
  bank_ifsc VARCHAR(11) NOT NULL,
  bank_last4 VARCHAR(4) NOT NULL,
  status VARCHAR(12) DEFAULT 'PENDING' NOT NULL,
  review_note VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  reviewed_at TIMESTAMP,
  CONSTRAINT uq_sellers_gstin UNIQUE (gstin)
);

